# Display the program title
print('Caesar Cipher Hacker, by Al Sweigart al@inventwithpython.com')

# Get the encrypted message from the user
print('Enter the encrypted Caesar cipher message to hack.')
# Convert input to uppercase so it matches the SYMBOLS list
message = input('> ').upper()

# Every possible symbol that can be encrypted/decrypted
# (This MUST match the SYMBOLS used in the encryption program)
SYMBOLS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'

# Loop through every possible key (from 0 up to the length of SYMBOLS - 1)
for key in range(len(SYMBOLS)):
    # This will store the decrypted message for the current key
    translated = ''

    # Loop through each symbol in the encrypted message
    for symbol in message:
        if symbol in SYMBOLS:
            # Find the position of the symbol in SYMBOLS
            num = SYMBOLS.find(symbol)
            # Subtract the key to decrypt
            num = num - key

            # Handle the wrap-around if num is less than 0
            if num < 0:
                num = num + len(SYMBOLS)

            # Add the decrypted symbol to our translated message
            translated = translated + SYMBOLS[num]
        else:
            # If the symbol is not in SYMBOLS (e.g., spaces or punctuation),
            # add it to the translated message unchanged
            translated = translated + symbol

    # Display the decryption results for the current key
    print('Key #{}: {}'.format(key, translated))

